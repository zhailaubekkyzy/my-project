const byId = (id) => DEMOS.find(d => d.id === id) || null;

/** The list for the author: what they can test on (no texts of the product beyond a short line). */
function list() {
  return DEMOS.map(d => ({ id: d.id, title: d.title, niche: d.niche, about: d.about, product: d.product.name, price: d.product.price_label }));
}

/**
 * The seller as if the demo business had bought it: the skeleton (methodology, steps, scenarios) stays,
 * everything about the business, the product, the expert and the FAQ comes from the demo. Nothing is saved.
 */
function overlay(project, demoId) {
  const d = byId(demoId);
  if (!project || !d) return project;
  const out = { ...project };
  for (const key of ['inheritedProfile', 'sellerNotes', 'puzzleAnswers']) delete out[key];
  out.offer = d.product.name;
  out.description = d.product.description;
  out.price_label = d.product.price_label;
  out.price_mode = 'fixed';
  out.payment_url = null; // a test: no real payment link
  out.access_url = null;
  out.faq = JSON.stringify(d.faq);
  out.inheritedBusiness = { name: `Пример: ${d.title}`, about: d.about, niche: d.niche };
  out.inheritedProduct = { name: d.product.name, result: d.product.result, format: d.product.format, duration: d.product.duration, installment: d.product.installment, guarantee: d.product.guarantee };
  out.demo = { id: d.id, title: d.title };
  return out;
}

module.exports = { DEMOS, list, byId, overlay };
